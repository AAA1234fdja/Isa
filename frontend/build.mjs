import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(fileURLToPath(import.meta.url));
const check = process.argv.includes('--check');
for (const [name, globalName] of [['layout','isaLayout'], ['appearance','isaAppearance'], ['sidebar','isaSidebar'], ['notifications','isaNotifications'], ['provider-utils','isaProviderUtils'], ['conversation-utils','isaConversationUtils'], ['provider-client','isaProviderClient'], ['pool-runner','isaPoolRunner'], ['project-store','isaProjectStore'], ['project-ui-module','isaProjectUI']]) {
  const bundleName = `__${globalName}Bundle`;
  const output = resolve(root, '../assets', `${name}.js`);
  const result = await build({
    entryPoints: [resolve(root, 'entries', `${name}.mjs`)],
    bundle: true, format: 'iife', platform: 'browser', target: ['es2020'],
    globalName: bundleName, write: false, legalComments: 'none',
    banner: {js: '// Generated by npm run build --prefix frontend; edit frontend/src instead.'},
    footer: {js: `const ${globalName} = ${bundleName}.controller;`},
  });
  const content = result.outputFiles[0].contents;
  if (check) {
    let current;
    try { current = await readFile(output); } catch { current = Buffer.alloc(0); }
    if (!current.equals(Buffer.from(content))) {
      console.error(`${output} is stale; run npm run build --prefix frontend`);
      process.exitCode = 1;
    }
  } else await writeFile(output, content);
}
