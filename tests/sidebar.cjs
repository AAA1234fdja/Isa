const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require(process.env.JSDOM_PATH || './ui/node_modules/jsdom');
const script = fs.readFileSync('assets/sidebar.js', 'utf8');
function setup(saved) {
  const dom = new JSDOM('<div class="app"><aside id="sidebar"><button id="collapseSidebar"></button></aside><button id="expandSidebar"></button><button id="menu"></button></div>', {url:'https://example.com/', runScripts:'outside-only'});
  const w = dom.window;
  let desktop = true;
  w.matchMedia = query => ({matches: query === '(min-width:701px)' ? desktop : !desktop});
  if (saved) w.localStorage.setItem('isa.sidebar.collapsed', saved);
  w.eval(script + '\nwindow.sidebarController = isaSidebar;');
  return {dom, w, desktop(value) { desktop = value; w.dispatchEvent(new w.Event('resize')); }};
}
const {dom, w, desktop} = setup('true');
const q = selector => w.document.querySelector(selector);
assert.equal(q('.app').classList.contains('sidebar-collapsed'), true);
assert.equal(q('#sidebar').inert, true);
assert.equal(q('#expandSidebar').getAttribute('aria-expanded'), 'false');
q('#expandSidebar').click();
assert.equal(q('.app').classList.contains('sidebar-collapsed'), false);
assert.equal(w.localStorage.getItem('isa.sidebar.collapsed'), 'false');
assert.equal(w.document.activeElement, q('#collapseSidebar'));
q('#collapseSidebar').click();
assert.equal(w.localStorage.getItem('isa.sidebar.collapsed'), 'true');
assert.equal(w.document.activeElement, q('#expandSidebar'));
desktop(false);
assert.equal(q('.app').classList.contains('sidebar-collapsed'), false);
assert.equal(q('#sidebar').inert, false);
q('#menu').click();
assert.equal(q('#menu').getAttribute('aria-expanded'), 'true');
w.sidebarController.close();
assert.equal(q('#sidebar').classList.contains('open'), false);
assert.equal(q('#menu').getAttribute('aria-expanded'), 'false');
q('#menu').click(); q('#collapseSidebar').click();
assert.equal(w.document.activeElement, q('#menu'));
assert.equal(q('#menu').getAttribute('aria-expanded'), 'false');
desktop(true);
assert.equal(q('.app').classList.contains('sidebar-collapsed'), true);
dom.window.close();
console.log('Sidebar controller preserves desktop, mobile, persistence and focus behavior');
