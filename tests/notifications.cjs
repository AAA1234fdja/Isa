const assert = require('node:assert/strict');
const fs = require('node:fs');
const {JSDOM} = require(process.env.JSDOM_PATH || './ui/node_modules/jsdom');
const dom = new JSDOM('<div id="toast"></div><dialog open></dialog><dialog open></dialog><dialog></dialog>', {runScripts:'outside-only'});
const w = dom.window, callbacks = new Map();
let next = 0;
w.setTimeout = fn => { const id = ++next; callbacks.set(id, fn); return id; };
w.clearTimeout = id => callbacks.delete(id);
w.eval(fs.readFileSync('assets/notifications.js', 'utf8') + '\nwindow.notifications = isaNotifications;');
const {notifications} = w, toast = w.document.querySelector('#toast');
notifications.show('one'); notifications.show('two');
assert.equal(toast.textContent, 'two');
assert.equal(toast.style.display, 'block');
assert.equal(callbacks.size, 1);
[...callbacks.values()][0]();
assert.equal(toast.style.display, 'none');
for (const data of [undefined, {}, {auditWarning:'__proto__'}, {auditWarning:'unknown'}]) notifications.reportAuditWarning(data);
assert.equal(w.document.querySelectorAll('.audit-warning').length, 0);
notifications.reportAuditWarning({auditWarning:'encrypted_details_incomplete'});
const warnings = w.document.querySelectorAll('dialog[open] .audit-warning');
assert.equal(warnings.length, 2);
assert.match(warnings[0].textContent, /no plaintext fallback/);
assert.equal(warnings[0].getAttribute('role'), 'alert');
notifications.reportAuditWarning({auditWarning:'both_incomplete'});
assert.equal(w.document.querySelectorAll('.audit-warning').length, 2);
assert.match(warnings[1].textContent, /action can continue/i);
assert.match(toast.textContent, /Audit event history and encrypted details/);
dom.window.close();
console.log('Notifications replace timers and surface recognized audit failures without blocking');
